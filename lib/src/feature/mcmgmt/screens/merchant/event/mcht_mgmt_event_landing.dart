const int wid=735;

@RoutePage()
class MchtMgmtEventLanding extends StatelessWidget {
  const MchtMgmtEventLanding({
    super.key,
    @PathParam.inherit('mchtEttyId') this.mchtEttyId,
  });

  final String? mchtEttyId;
